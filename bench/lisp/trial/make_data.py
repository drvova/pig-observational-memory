"""make_data.py OM WORK OUT MANUAL: reads the trial memory through the real tool (one call per day, so
no result is cut) and writes it as Lisp data for mock/om.lisp, so the mock answers from the same rows
(the scratch WORK path in file targets becomes /work); MANUAL gets the Go manual the model is shown:
the tool's own manual (empty code) and describe() of the values the tasks read."""
import json
import os
import sys

from omcall import om_call

DAYS = ["2026-05-01", "2026-05-02", "2026-05-03", "2026-05-04", "2026-05-05"]

NOTES = """q := strconv.Quote
list := func(xs []string) string {
	out := []string{}
	for _, x := range xs {
		out = append(out, q(x))
	}
	return "[" + strings.Join(out, ",") + "]"
}
for _, n := range om.Notes(om.Since(`DAY`).Until(`DAY`).Limit(200)).Rows {
	fmt.Printf("{\\"id\\":%s,\\"when\\":%s,\\"kind\\":%s,\\"subject\\":%s,\\"content\\":%s,\\"status\\":%s,\\"event_date\\":%s,\\"origin\\":%s,\\"outcome\\":%s,\\"tool\\":%s,\\"target\\":%s,\\"source\\":%s,\\"source_role\\":%s,\\"anchor\\":%s,\\"relevance\\":%s,\\"superseded_by\\":%s,\\"supersedes\\":%s}\\n",
		q(n.ID), q(n.When), q(n.Kind), q(n.Subject), q(n.Content), q(n.Status), q(n.EventDate), q(n.Origin), q(n.Outcome), q(n.Tool), q(n.Target), q(n.Source), q(n.SourceRole), q(n.Anchor), q(n.Relevance), list(n.SupersededBy), list(n.Supersedes))
}
"""

HISTORY = """for _, e := range om.History(om.Since(`DAY`).Until(`DAY`).Limit(200)).Rows {
	fmt.Printf("{\\"id\\":%s,\\"when\\":%s,\\"role\\":%s,\\"text\\":%s}\\n", strconv.Quote(e.ID), strconv.Quote(e.When), strconv.Quote(e.Role), strconv.Quote(e.Text))
}
"""

IDS = """fmt.Println(strings.Join(om.LIST(om.Limit(200)).IDs(), " "))"""


def call(om, work, code):
    err, text = om_call(om, work, code)
    if err:
        sys.exit("om call failed: " + text)
    return text


WORK = None


def lisp(v):
    if isinstance(v, str):
        v = v.replace(WORK, "/work")
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "(" + " ".join(lisp(x) for x in v) + ")"
    if isinstance(v, dict):
        return "(" + " ".join(":" + k.replace("_", "-") + " " + lisp(x) for k, x in v.items()) + ")"
    raise TypeError(v)


def main():
    global WORK
    om, work, out, manual = sys.argv[1:5]
    WORK = os.path.realpath(work)
    notes, history = [], []
    for day in DAYS:
        notes += [json.loads(l) for l in call(om, work, NOTES.replace("DAY", day)).splitlines() if l]
    for day in reversed(DAYS):
        history += [json.loads(l) for l in call(om, work, HISTORY.replace("DAY", day)).splitlines() if l]
    data = {"notes": notes, "history": history}
    for name in ["Files", "Commits", "Attempts"]:
        data[name.lower()] = call(om, work, IDS.replace("LIST", name)).split()
    with open(out, "w") as f:
        f.write(";; Generated by make_data.py from memory.jsonl through the real memory tool.\n")
        for k, v in data.items():
            f.write("(:" + k + "\n " + "\n ".join(lisp(x) for x in v) + ")\n" if k in ("notes", "history")
                    else "(:" + k + " " + lisp(v) + ")\n")
    with open(manual, "w") as f:
        f.write(call(om, work, "").rstrip() + "\n")
        for v in ["om.Note{}", "om.NoteList{}", "om.Entry{}", "om.EntryList{}"]:
            f.write("\n" + call(om, work, "describe(" + v + ")").rstrip() + "\n")
    print(len(notes), "notes,", len(history), "history entries")


main()
