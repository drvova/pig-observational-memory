package om

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/doc"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// writeDocs regenerates docs_gen.go instead of comparing it (go generate ./internal/om).
var writeDocs = flag.Bool("write", false, "write docs_gen.go")

//go:generate go test . -run ^TestDocsAreUpToDate$ -args -write

// TestDocsAreUpToDate regenerates the doc table from om's sources and fails on a diff, and when
// an exported function, type or method has no doc comment (docs/code-tool.md, "describe(x) and
// its docs"). The generator runs as this test since PiG refuses an extension module holding a
// main package.
func TestDocsAreUpToDate(t *testing.T) {
	src, missing, err := generateDocs(".")
	if err != nil {
		t.Fatal(err)
	}
	if len(missing) > 0 {
		t.Errorf("exported om symbols without a doc comment: %s", strings.Join(missing, ", "))
	}
	if *writeDocs {
		if err := os.WriteFile("docs_gen.go", src, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile("docs_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(have, src) {
		t.Fatal("docs_gen.go differs from om's sources: run go generate ./internal/om")
	}
}

// generateDocs reads every non-test, non-generated source of om in dir and writes the doc table:
// the synopsis and signature of every exported function, type, method and documented field.
func generateDocs(dir string) ([]byte, []string, error) {
	fset := token.NewFileSet()
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, nil, err
	}
	var files []*ast.File
	for _, name := range names {
		base := filepath.Base(name)
		if strings.HasSuffix(base, "_test.go") || base == "docs_gen.go" {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, parser.ParseComments)
		if err != nil {
			return nil, nil, err
		}
		files = append(files, f)
	}
	pkg, err := doc.NewFromFiles(fset, files, "om")
	if err != nil {
		return nil, nil, err
	}
	entries := map[string][2]string{}
	var missing []string
	sig := func(ft *ast.FuncType) string {
		var b bytes.Buffer
		_ = printer.Fprint(&b, fset, ft)
		return strings.TrimPrefix(b.String(), "func")
	}
	addFunc := func(key string, f *doc.Func) {
		if !ast.IsExported(f.Name) {
			return
		}
		if strings.TrimSpace(f.Doc) == "" {
			missing = append(missing, key)
		}
		entries[key] = [2]string{f.Name + sig(f.Decl.Type), pkg.Synopsis(f.Doc)}
	}
	for _, f := range pkg.Funcs {
		addFunc(f.Name, f)
	}
	for _, typ := range pkg.Types {
		if !ast.IsExported(typ.Name) {
			continue
		}
		if strings.TrimSpace(typ.Doc) == "" {
			missing = append(missing, typ.Name)
		}
		entries[typ.Name] = [2]string{"type " + typ.Name, pkg.Synopsis(typ.Doc)}
		for _, f := range typ.Funcs {
			addFunc(f.Name, f)
		}
		for _, m := range typ.Methods {
			addFunc(typ.Name+"."+m.Name, m)
		}
		for _, spec := range typ.Decl.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				continue
			}
			for _, field := range st.Fields.List {
				text := field.Doc.Text()
				if text == "" {
					text = field.Comment.Text()
				}
				var b bytes.Buffer
				_ = printer.Fprint(&b, fset, field.Type)
				for _, n := range field.Names {
					if ast.IsExported(n.Name) {
						entries[typ.Name+"."+n.Name] = [2]string{n.Name + " " + b.String(), pkg.Synopsis(text)}
					}
				}
			}
		}
	}
	keys := make([]string, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b bytes.Buffer
	b.WriteString("// Code generated by TestDocsAreUpToDate (go generate ./internal/om). DO NOT EDIT.\n\npackage om\n\n")
	b.WriteString("// docs are each exported symbol's signature and the synopsis of its doc comment, by name\n// (Type.Method and Type.Field for a method or field).\nvar docs = map[string][2]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: {%q, %q},\n", k, entries[k][0], entries[k][1])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	sort.Strings(missing)
	return src, missing, err
}
